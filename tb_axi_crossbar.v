module tb_axi_crossbar ();
  `timescale 1ns / 1ps
	reg clk;
	reg reset_n;
	
	//Write Address Channel
	reg [31:0]	 m0_AWAddr;
	reg    		 m0_AWValid;
	reg 			 m1_AWValid;
	wire   		 m0_AWReady;
	
	reg [31:0]   m0_WData;
	reg [3:0]    m0_WStrb;
	wire 			 m0_WReady;
	reg 			 m0_WValid;
	reg 			 s0_WReady;
	
	wire[31:0]	 s0_AWAddr;
	wire 	 		 s0_AWValid;
	reg   		 s0_AWReady;
	
	reg [1:0]	 s0_BResp;
	reg 			 s0_BValid;
	reg 			 m0_BReady;
	wire[1:0] 	 m0_BResp;
	wire 			 m0_BValid;
	wire 			 s0_BReady;
	
	axi_crossbar uut (
	.clk 			(clk),
	.reset_n		(reset_n),
	.m0_AWAddr  (m0_AWAddr),
	.m1_AWValid (m1_AWValid),
	.m0_AWValid (m0_AWValid),
	.m0_AWReady (m0_AWReady),
	.m0_WData   (m0_WData),
	.m0_WValid  (m0_WValid),
	.m0_WReady 	(m0_WReady),
	.m0_WStrb   (m0_WStrb),
	.s0_WReady  (s0_WReady),
	.s0_BResp  	(s0_BResp),
	.s0_BValid  (s0_BValid),
	.m0_BReady  (m0_BReady),
	.m0_BResp   (m0_BResp),
	.m0_BValid  (m0_BValid),
   .s0_BReady  (s0_BReady),
	.s0_AWAddr  (s0_AWAddr),
	.s0_AWValid (s0_AWValid),
	.s0_AWReady (s0_AWReady)
	);
	
	//Begin testing
	always #5 clk = ~clk;
	
	initial begin
	clk = 0;
	reset_n = 0;
	m0_AWAddr = 0;
	m0_AWValid = 0;
	s0_AWReady = 0;
	m1_AWValid = 0;
	m0_WValid  = 0;
	m0_WData   = 0;
	m0_WStrb   = 0;
	s0_WReady  = 0;
	s0_BResp   = 0;
	s0_BValid  = 0;
	m0_BReady  = 0;
	#20;
	reset_n = 1;
	
	#10;
	m0_AWAddr = 32'h00001000;
	m0_AWValid = 1;
	m1_AWValid = 0;
	m0_WData = 32'hDEAD_BEEF;
	m0_WStrb = 4'b1111;
	m0_WValid = 1;
	
	s0_BResp = 2'b00;
	s0_BValid = 1;
	
	#10;
	s0_AWReady = 1;
	s0_WReady = 1;
	m0_BReady = 1;
	#10;
	//Reset
	m0_AWValid = 0;
	s0_AWReady = 0;
	m0_AWValid = 0;
	m0_WValid = 0;
	s0_AWReady = 0;
	s0_WReady = 0;
	s0_BValid = 0;
	m0_BReady = 0;
	
	// --- START OF TEST 2 (Decode Error) ---
	m0_AWAddr = 32'hFFFF_FFFF;
	m0_WData  = 32'hBAD_C0DE;

	// Assert all phases simultaneously to hold the arbiter grant
	m0_AWValid = 1'b1;
	m0_WValid  = 1'b1;
	m0_BReady  = 1'b1;

	// Wait for the fabricated response
	wait (m0_BValid == 1'b1);
	#1;

	if (m0_BResp == 2'b11) begin
		  $display("SUCCESS: DECERR (2'b11) correctly generated by crossbar!");
	end else begin
		  $display("FAIL: Expected DECERR, got %b", m0_BResp);
	end

	#10;
	// Clear the bus
	m0_AWValid = 1'b0;
	m0_WValid  = 1'b0;
	m0_BReady  = 1'b0;
	$stop;
	end
	
endmodule
